const storageKey = "portfolio-language";
const htmlElement = document.documentElement;
const langButtons = document.querySelectorAll(".lang-button");
const menuToggle = document.querySelector(".menu-toggle");
const navPanel = document.querySelector(".nav-panel");
const navLinks = document.querySelectorAll(".nav-list a");
const translationElements = document.querySelectorAll("[data-i18n]");
const expCards = document.querySelectorAll(".exp-card[data-expandable]");

const saveLanguage = (lang) => localStorage.setItem(storageKey, lang);
const getSavedLanguage = () => {
  const saved = localStorage.getItem(storageKey);
  return saved === "en" ? "en" : "pt";
};

const setActiveLanguageButton = (lang) => {
  langButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });
};

const translatePage = (lang) => {
  if (!translations[lang]) lang = "pt";
  htmlElement.lang = lang === "en" ? "en" : "pt-BR";
  document.title = translations[lang].pageTitle;

  translationElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (!key) return;
    const text = translations[lang][key];
    if (text !== undefined) element.textContent = text;
  });

  expCards.forEach((card) => {
    const toggle = card.querySelector(".exp-toggle");
    if (!toggle) return;
    const expanded = card.classList.contains("expanded");
    toggle.textContent = translations[lang][expanded ? "toggleLess" : "toggleMore"];
  });

  setActiveLanguageButton(lang);
  saveLanguage(lang);
};

const toggleNav = () => {
  const isOpen = navPanel.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
};

const closeNav = () => {
  navPanel.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
};

const toggleCard = (card) => {
  const toggle = card.querySelector(".exp-toggle");
  const expanded = card.classList.toggle("expanded");
  card.setAttribute("aria-expanded", expanded ? "true" : "false");
  toggle.setAttribute("aria-expanded", expanded ? "true" : "false");
  const lang = getSavedLanguage();
  toggle.textContent = translations[lang][expanded ? "toggleLess" : "toggleMore"];
};

menuToggle.addEventListener("click", toggleNav);
navLinks.forEach((link) => link.addEventListener("click", closeNav));
langButtons.forEach((button) => {
  button.addEventListener("click", () => {
    translatePage(button.dataset.lang);
    closeNav();
  });
});

expCards.forEach((card) => {
  const toggle = card.querySelector(".exp-toggle");
  if (!toggle) return;

  toggle.addEventListener("click", (event) => {
    event.stopPropagation();
    toggleCard(card);
  });

  card.addEventListener("click", (event) => {
    if (event.target === toggle) return;
    toggleCard(card);
  });

  card.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      toggleCard(card);
    }
  });
});

window.addEventListener("resize", () => {
  if (window.innerWidth >= 768) closeNav();
});

translatePage(getSavedLanguage());
